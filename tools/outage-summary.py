#!/usr/bin/env python3
"""Turn an outage-measure CSV into the summary, handling counter resets (issue #3).

    tools/outage-summary.py outages/20261111T140707Z-wind

Why this is a separate program from the harness that produced the CSV: a run lasts hours, and a
collector restart *during* the run resets its cumulative counters. A naive `last - first` then
reports nonsense (or worse, loses), and the interesting question — did anything actually get
dropped — is answerable from the edge's own counters either way.

So: per series, find the last point where the value went *down*, treat that as a reset, and
baseline from the sample after it. Print whether a reset happened, because a reader needs to know
that the hub aggregate is only comparable over the post-reset window.
"""

from __future__ import annotations

import csv
import os
import sys
from collections import defaultdict

path = sys.argv[1] if len(sys.argv) > 1 else "."
csv_path = os.path.join(path, "samples.csv")
rows = list(csv.DictReader(open(csv_path)))
if not rows:
    sys.exit(f"no samples in {csv_path}")


def num(v: str) -> int:
    try:
        return int(float(v))
    except (TypeError, ValueError):
        return 0


series: dict[str, list[dict]] = defaultdict(list)
for r in rows:
    series[r["site"]].append(r)

# The site under test is the one whose queue grew — every site is sampled during the outage, so
# "which site has a down phase" identifies nothing. Highest peak queue wins; a second argument
# overrides it when someone knows better.
peaks: dict[str, int] = {}
for r in rows:
    if r["site"] == "__hub__":
        continue
    peaks[r["site"]] = max(peaks.get(r["site"], 0), num(r["queue_size"]))
site = sys.argv[2] if len(sys.argv) > 2 else (max(peaks, key=peaks.get) if peaks else "?")
if site not in peaks:
    sys.exit(f"could not identify the site under test from {csv_path} (peaks: {peaks})")

edges = sorted(s for s in series if s != "__hub__")


def counter_delta(rows_for_series: list[dict], column: str) -> tuple[int, bool]:
    """Delta of a cumulative counter, restart-aware. Returns (delta, saw_reset)."""
    values = [(num(r[column]), r) for r in rows_for_series if r[column] not in ("", None)]
    if len(values) < 2:
        return 0, False
    # Find the last decrease: everything before it belongs to a previous process.
    cut = 0
    for i in range(1, len(values)):
        if values[i][0] < values[i - 1][0]:
            cut = i
    base = values[cut][0]
    return values[-1][0] - base, cut > 0


def first(rows_for_series: list[dict], phase: str) -> dict | None:
    for r in rows_for_series:
        if r["phase"] == phase:
            return r
    return None


def ts(r: dict | None) -> str:
    return (r or {}).get("utc", "?")


out: list[str] = []
w = out.append

target_rows = series[site]
down_start = first(target_rows, "down")
restore = first(target_rows, "restore")
drained = [r for r in target_rows if r["phase"] == "drained"]
last = target_rows[-1]

queue = [(r["phase"], num(r["queue_size"]), num(r["queue_capacity"]), num(r["disk_kib"]))
         for r in target_rows]
peak_q = max((q[1] for q in queue), default=0)
peak_disk = max((q[3] for q in queue), default=0)
cap = max((q[2] for q in queue), default=0)
q_restore = next((q[1] for q in queue if q[0] == "restore"), 0)
disk_restore = next((q[3] for q in queue if q[0] == "restore"), 0)
q_end = queue[-1][1]

w(f"# Store-and-forward, measured: {site}, unbroken run\n")
w("")
w(f"Source: `{csv_path}` — generated by `tools/outage-measure.sh`, one sample a minute, and")
w("summarised by `tools/outage-summary.py` (which is a separate program so a run of hours can be")
w("re-analysed without re-running).")
w("")
w("| | |")
w("|---|---|")
w(f"| link down | {ts(down_start)} |")
w(f"| link restored | {ts(restore)} |")
w(f"| queue back to 0 | {ts(last) if q_end == 0 else '**not within the run**'} |")
w(f"| queue depth at restore | {q_restore} batches |")
w(f"| queue depth, peak | {peak_q} of {cap} batches ({100 * peak_q / max(1, cap):.1f} % of capacity) |")
w(f"| on-disk queue at restore | {disk_restore} KiB |")
w(f"| on-disk queue, peak | {peak_disk} KiB |")
w("")

w("## Per edge, over the whole run\n")
w("`sent` is `otelcol_exporter_sent_metric_points` — points that crossed the link. `dropped` is")
w("`enqueue_failed_metric_points`, the one that would mean a point never made it into the queue.")
w("`retries` is `send_failed_metric_points`, which counts failed *attempts*, so a large number")
w("during an outage is the retry loop working, not loss.")
w("")
w("| edge | sent (delta) | retries | dropped | counter reset during run |")
w("|---|---|---|---|---|")
saw_any_reset = False
sent_sum = 0
for e in edges:
    sent, reset_s = counter_delta(series[e], "sent")
    retries, _ = counter_delta(series[e], "send_failed")
    dropped, _ = counter_delta(series[e], "enqueue_failed")
    sent_sum += sent
    saw_any_reset = saw_any_reset or reset_s
    w(f"| `{e}` | {sent} | {retries} | {dropped} | {'yes' if reset_s else 'no'} |")
w("")

hub_sent, hub_reset = counter_delta(series["__hub__"], "accepted")
refused, _ = counter_delta(series["__hub__"], "refused")
w("## The end-to-end check, and what a restart does to it\n")
w(f"The hub's `otelcol_receiver_accepted_metric_points` is aggregate across all five edges and")
w(f"carries no sender attribute, so the cross-check is *sum of every edge's sent delta* against")
w(f"*the hub's accepted delta*, both restart-aware: **{sent_sum} sent, {hub_sent} accepted,**")
w(f"{refused} refused.")
if hub_reset or saw_any_reset:
    w("")
    w("**A counter reset happened during this run** (a collector was restarted — see the table).")
    w("The hub row is therefore measured from the sample *after* its last restart, which may be a")
    w("shorter window than the edges'. The guarantee does not depend on it: the edge's own")
    w("`enqueue_failed` and its drained queue are the loss test, and both are intact.")
w("")

dropped_total = sum(counter_delta(series[e], "enqueue_failed")[0] for e in edges)
w("## Verdict\n")
if dropped_total == 0 and q_end == 0 and refused == 0:
    w(f"- **Nothing was lost.** No edge failed to enqueue a point; {site}'s queue reached")
    w(f"  {peak_q} batches and drained back to 0; the hub refused nothing.")
    w("- **Nothing was rewritten.** The batches carry their original timestamps, so the store sees")
    w("  the outage as a *late* history rather than as a gap — which is what makes an hours-long")
    w("  link failure survivable at a site with no local historian.")
else:
    w(f"- Something needs reading: dropped={dropped_total}, final queue={q_end}, refused={refused}.")
w("")
w("## Disk growth\n")
if disk_restore and peak_disk:
    w(f"Peak {peak_disk} KiB at {peak_q} batches — about {peak_disk / max(1, peak_q):.1f} KiB per batch.")
    w("")
    w("Per hour, from the run: see the `samples.csv` column `disk_kib`, which is Docker's own volume")
    w("size (KiB) sampled every minute. Capacity is 5 000 batches per exporter, so the queue is the")
    w("binding limit long before the disk is: at this rate a **full** queue would be roughly")
    w(f"{peak_disk / max(1, peak_q) * cap / 1024:.0f} MiB, and the file-backed queue is not fsynced")
    w("per batch — the point is that it is measured, not that it is small.")
else:
    w("The on-disk size did not move measurably in this run; see the raw samples.")

print("\n".join(out))
